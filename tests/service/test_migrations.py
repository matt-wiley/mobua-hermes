"""AC-7, AC-8: migrations run from the installed package, and the developer path still checks."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text

from news.service.db import alembic_config, create_engine_for, migrate

REPO_ROOT = Path(__file__).resolve().parents[2]


def test_migrate_reaches_head_outside_the_repository(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(tmp_path)
    engine = create_engine_for(f"sqlite:///{tmp_path / 'news.db'}")

    migrate(engine)

    with engine.connect() as connection:
        current = MigrationContext.configure(connection).get_current_revision()
    engine.dispose()
    assert current is not None
    assert current == ScriptDirectory.from_config(alembic_config()).get_current_head()


def _migrated_database_url(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    url = f"sqlite:///{tmp_path / 'news.db'}"
    engine = create_engine_for(url)
    migrate(engine)
    engine.dispose()
    monkeypatch.setenv("NEWS_DATABASE_URL", url)
    return url


def test_root_alembic_ini_finds_no_differences_from_the_models(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _migrated_database_url(tmp_path, monkeypatch)

    # Raises AutogenerateDiffsDetected if the models and the migrations disagree.
    command.check(Config(REPO_ROOT / "alembic.ini"))


def test_root_alembic_ini_reports_a_schema_the_models_do_not_describe(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    engine = create_engine_for(_migrated_database_url(tmp_path, monkeypatch))
    with engine.begin() as connection:
        connection.execute(text("CREATE TABLE stray (id INTEGER PRIMARY KEY)"))
    engine.dispose()

    with pytest.raises(AutogenerateDiffsDetected, match="stray"):
        command.check(Config(REPO_ROOT / "alembic.ini"))
